/** スコア帯を判定 */
function getScoreTier(score: number): keyof typeof SCORE_PHRASES {
  if (score >= 80) return 'veryHigh';
  if (score >= 60) return 'high';
  if (score >= 40) return 'mid';
  if (score >= 20) return 'low';
  return 'veryLow';
}

/** 占い結果からタイプキーを抽出 */
export function extractTypeKey(fortuneId: string, detailsTotal: string, characterName?: string, bloodType?: string): string {
  switch (fortuneId) {
    case 'honDoubutsu':
      return characterName || 'ドルフィン';
    case 'seiza': {
      const seizaMap: Record<string, string> = {
        '牡羊座': 'aries', '牡牛座': 'taurus', '双子座': 'gemini', '蟹座': 'cancer',
        '獅子座': 'leo', '乙女座': 'virgo', '天秤座': 'libra', '蠍座': 'scorpio',
        '射手座': 'sagittarius', '山羊座': 'capricorn', '水瓶座': 'aquarius', '魚座': 'pisces',
      };
      for (const [name, id] of Object.entries(seizaMap)) {
        if (detailsTotal.includes(name)) return id;
      }
      return 'aries';
    }
    case 'tarot': {
      const match = detailsTotal.match(/【(.+?)】/);
      return match?.[1] || '愚者';
    }
    case 'bloodType':
      return bloodType || 'A';
    case 'numerology': {
      const match = detailsTotal.match(/誕生数(\d+)/);
      return match?.[1] || '1';
    }
    case 'omikuji': {
      const match = detailsTotal.match(/【(.+?)】/);
      return match?.[1] || '吉';
    }
    default:
      return '';
  }
}

/** アドバイス生成 */
export function generateDailyAdvice(
  fortuneId: string,
  typeKey: string,
  totalScore: number,
  date: string
): string {
  const seed = stringToSeed(`advice_${fortuneId}_${typeKey}_${date}`);
  const rand = seededRandom(seed);

  // タイプ別フレーズ取得
  const typePhrases = TYPE_PHRASES[fortuneId]?.[typeKey];
  const typePhrase = typePhrases
    ? typePhrases[Math.floor(rand() * typePhrases.length)]
    : '今日のあなたは、';

  // スコア帯フレーズ取得
  const tier = getScoreTier(totalScore);
  const scorePhrases = SCORE_PHRASES[tier];
  const scorePhrase = scorePhrases[Math.floor(rand() * scorePhrases.length)];

  // 結びフレーズ取得
  const endingPhrase = ENDING_PHRASES[Math.floor(rand() * ENDING_PHRASES.length)];

  return `${typePhrase}${scorePhrase}${endingPhrase}`;
}

export default generateDailyAdvice;
